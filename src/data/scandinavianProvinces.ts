/**
 * Risolutore toponomastico dinamico per tutti i distretti e province della Scandinavia.
 */
export function resolveScandinavianToponym(
  id: string,
  rawName: string,
  normKey: string,
  owner: string,
  yearStep: number = 0
): { name: string; adminTitle?: string; note?: string } | null {
  const normId = String(id || '').trim().toUpperCase();
  const rawLower = String(rawName || '').toLowerCase();
  const nKey = normKey || rawLower.replace(/[^a-z0-9]/g, '_');

  // Ricerca prioritaria per codice NUTS esatto
  let def = SCANDINAVIAN_DISTRICTS_CATALOG.find(d => d.nuts === normId);

  // Ricerca secondaria per chiavi toponomastiche
  if (!def) {
    def = SCANDINAVIAN_DISTRICTS_CATALOG.find(d => 
      d.keys.some(k => nKey === k || nKey.includes(k) || rawLower.includes(k))
    );
  }

  if (!def) return null;

  // Gestione dinamica temporale post-transizione (step >= 6: giu 1940 post-Weserübung / Mosca)
  const isPost = def.transitionStep !== undefined && yearStep >= def.transitionStep;

  if (isPost && def.postName) {
    return {
      name: def.postName,
      adminTitle: def.postAdminTitle || def.preAdminTitle,
      note: def.postNote || def.preNote,
    };
  }

  return {
    name: def.name,
    adminTitle: def.preAdminTitle,
    note: def.preNote,
  };
}

/**
 * Popola il dizionario storico con tutti i toponimi scandinavi.
 */
export function populateScandinavianToponyms(dict: Record<string, Record<string, ToponymMatch>>): void {
  for (const item of SCANDINAVIAN_DISTRICTS_CATALOG) {
    const owner = item.country;
    if (!dict[owner]) dict[owner] = {};

    const match: ToponymMatch = {
      historicalName: item.name,
      adminTitle: item.preAdminTitle,
      historicalNote: item.preNote,
    };

    for (const key of item.keys) {
      dict[owner][key] = match;
    }

    // Aggiungi anche nel dizionario tedesco per territori occupati post-aprile/giugno 1940
    if (item.postName && item.postOwner === 'GER') {
      if (!dict['GER']) dict['GER'] = {};
      dict['GER'][item.keys[0]] = {
        historicalName: item.postName,
        adminTitle: item.postAdminTitle,
        historicalNote: item.postNote,
      };
    }
  }
}
