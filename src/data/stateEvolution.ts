type DynamicLeader = string | ((s?: number) => string);

interface InternalRule extends Omit<GovernanceRule, 'leader'> {
  leader?: DynamicLeader;
}

export function applyChronologicalStateOverrides(meta: OwnerConfig, step: number): OwnerConfig {
  const id = (meta.id || '').toUpperCase();
  if (!id) return meta;

  let next = meta;
  for (const rule of GOVERNANCE_RULES as readonly InternalRule[]) {
    if (step < rule.minStep || step > rule.maxStep) continue;
    if (!rule.ids.includes(id)) continue;

    const resolvedLeader = typeof rule.leader === 'function' ? rule.leader(step) : rule.leader;
    const resolvedLabel =
      rule.l !== undefined
        ? typeof rule.l === 'function'
          ? () => (rule.l as (s: number, prev: OwnerConfig) => string)(step, next)
          : () => rule.l as string
        : next.l;

    next = {
      ...next,
      ...(rule.f !== undefined ? { f: rule.f } : {}),
      ...(rule.shortName !== undefined ? { shortName: rule.shortName } : {}),
      ...(resolvedLeader !== undefined ? { leader: resolvedLeader } : {}),
      ...(rule.capital !== undefined ? { capital: rule.capital } : {}),
      ...(rule.tier !== undefined ? { tier: rule.tier } : {}),
      ...(rule.overlordCode !== undefined ? { overlordCode: rule.overlordCode } : {}),
      ...(rule.isSubject !== undefined ? { isSubject: rule.isSubject } : {}),
      l: resolvedLabel,
    };
  }
  return next;
}
